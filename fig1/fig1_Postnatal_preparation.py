def file_sha256(path):
    h=hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda:handle.read(1024*1024),b''):
            h.update(block)
    return h.hexdigest()

def matrix_hash(matrix,data_dtype='<i4'):
    matrix=matrix.copy().tocsr()
    matrix.sort_indices()
    h=hashlib.sha256()
    for values,dtype in [(matrix.shape,'<i8'),(matrix.indptr,'<i8'),(matrix.indices,'<i8'),(matrix.data,data_dtype)]:
        h.update(np.asarray(values,dtype=dtype).tobytes())
    return h.hexdigest()

