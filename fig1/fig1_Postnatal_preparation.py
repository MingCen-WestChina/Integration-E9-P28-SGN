# Set postnatal_prepared.h5ad, generated here and consumed by the postnatal and whole-period integration notebooks.
PREPARED_FILE = ROOT



def fingerprints(adata):
    return {
        "cells": hashlib.sha256(
            "\n".join(adata.obs_names).encode()
        ).hexdigest(),
        "genes": hashlib.sha256(
            "\n".join(adata.var_names).encode()
        ).hexdigest(),
        "counts": matrix_hash(adata.layers["counts"]),
    }

def plain_containers(value):
    # Convert nested OrderedDict and other mappings without dropping content.
    if isinstance(value, Mapping):
        return {
            key: plain_containers(item)
            for key, item in value.items()
        }

    if isinstance(value, (list, tuple)):
        return [plain_containers(item) for item in value]

    return value

def export_copy(source):
    saved = source.copy()
    saved.uns = plain_containers(saved.uns)

    # Change index titles only in the export copy.
    saved.obs.index.name = None
    saved.var.index.name = None

    for key in list(saved.obsm):
        if key.startswith("X_umap"):
            del saved.obsm[key]

    # Preserve nullable and mixed metadata values.
    encoded = {}

    for axis in ("obs", "var"):
        frame = getattr(saved, axis)
        encoded[axis] = []

        for column in frame:
            series = frame[column]

            if isinstance(
                series.dtype, (pd.Float32Dtype, pd.Float64Dtype)
            ):
                frame[column] = series.to_numpy(
                    dtype=float, na_value=np.nan
                )

            elif series.dtype == object:
                values = series.dropna()

                if len(values) and all(
                    isinstance(v, (bool, np.bool_)) for v in values
                ):
                    frame[column] = series.astype("boolean")

                elif all(isinstance(v, str) for v in values):
                    frame[column] = series.astype("string")

                else:
                    frame[column] = series.map(
                        lambda v: pd.NA if pd.isna(v) else json.dumps(v)
                    ).astype("string")
                    encoded[axis].append(column)

        encoded[axis] = np.asarray(encoded[axis], dtype=str)

    saved.uns["postnatal_serialization"] = encoded
    return saved

def decode_metadata(saved):
    for axis, columns in saved.uns.get(
        "postnatal_serialization", {}
    ).items():
        for column in columns:
            frame = getattr(saved, axis)
            frame[column] = frame[column].astype(object).map(
                lambda v: np.nan if pd.isna(v) else json.loads(v)
            )

    return saved

def read_result(path):
    restored = decode_metadata(ad.read_h5ad(path))

    assert fingerprints(restored) == restored.uns["reuse_fingerprints"]
    assert (restored.X != restored.layers["counts"]).nnz == 0
    assert not any(
        key.startswith("X_umap") for key in restored.obsm
    )

    return restored

def verify_result(source, restored):
    assert fingerprints(restored) == fingerprints(source)
    assert (restored.X != restored.layers["counts"]).nnz == 0

    for axis in ("obs", "var"):
        left = getattr(source, axis)
        right = getattr(restored, axis)

        assert left.columns.equals(right.columns)
        assert left.index.tolist() == right.index.tolist()

        for column in left:
            x, y = left[column], right[column]

            assert np.array_equal(x.isna(), y.isna()), column
            keep = x.notna()
            assert x[keep].tolist() == y[keep].tolist(), column

            if isinstance(x.dtype, pd.CategoricalDtype):
                assert x.cat.categories.equals(y.cat.categories), column
                assert x.cat.ordered == y.cat.ordered, column

    for key in ("X_scvi", "X_scanvi"):
        if key in source.obsm:
            np.testing.assert_array_equal(
                source.obsm[key], restored.obsm[key]
            )

    if "saved_training_history" in source.uns:
        for method, history in source.uns["saved_training_history"].items():
            pd.testing.assert_frame_equal(
                history,
                restored.uns["saved_training_history"][method],
            )

def write_result(adata, path):
    exported = export_copy(adata)
    exported.uns["reuse_fingerprints"] = fingerprints(adata)

    # Validate the complete export before touching the output file.
    with ad.settings.override(allow_write_nullable_strings=True):
        with h5py.File(io.BytesIO(), "w") as handle:
            write_elem(
                handle,
                "adata",
                exported,
                dataset_kwargs={"compression": "gzip"},
            )
            checked = decode_metadata(read_elem(handle["adata"]))
            verify_result(adata, checked)

        exported.write_h5ad(
            path,
            compression="gzip",
            convert_strings_to_categoricals=False,
        )

    verify_result(adata, read_result(path))

